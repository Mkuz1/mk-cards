// Packs everything in ./public into src/assets.generated.js so the Worker can serve the site itself.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const root = new URL('../public/', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8',
  // The print engine's shaping library and fonts.
  '.mjs': 'text/javascript; charset=utf-8', '.wasm': 'application/wasm', '.ttf': 'font/ttf',
};

const assets = {};
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const file = join(dir, name);
    if (statSync(file).isDirectory()) { walk(file); continue; }
    const type = TYPES[extname(name)];
    if (!type) throw new Error(`No content type for ${file}`);
    const bytes = readFileSync(file);
    assets['/' + relative(root, file).split('\\').join('/')] = {
      type,
      etag: `"${createHash('sha256').update(bytes).digest('hex').slice(0, 16)}"`,
      base64: bytes.toString('base64'),
    };
  }
};
walk(root);

writeFileSync(new URL('../src/assets.generated.js', import.meta.url),
  `// Generated by scripts/build-assets.mjs — do not edit.\nexport const ASSETS = ${JSON.stringify(assets, null, 1)};\n`);
// The same QR library the page uses, copied as CommonJS so the Worker can import it to make QR files.
copyFileSync(new URL('../public/vendor/qrcode.js', import.meta.url), new URL('../src/qrcode.generated.cjs', import.meta.url));

// The pass templates ship inside both apps too, so new passes can be made offline from the same list.
const templates = new URL('../public/pass-templates.json', import.meta.url);
for (const target of ['../../ios/MKCards/', '../../android/app/src/main/assets/']) {
  const dir = new URL(target, import.meta.url);
  if (existsSync(dir)) copyFileSync(templates, new URL('pass-templates.json', dir));
}

console.log(`Bundled ${Object.keys(assets).length} files.`);
